"""Regenerate the run_script fuzz dictionary and seed corpus from the source tree.

    python3 fuzz/gen_corpus.py        (run from kleos-core/)

Writes fuzz/cozoscript.dict (grammar literals, builtin functions, fixed rules)
and fuzz/seeds/run_script/ (CozoScript literals found in tests and docs).
"""

import hashlib
import pathlib
import re
import warnings

# Test sources contain escapes Python does not know (e.g. "\\q"); keep them literally.
warnings.filterwarnings("ignore", category=DeprecationWarning)

CORE = pathlib.Path(__file__).resolve().parent.parent
FUZZ = CORE / "fuzz"
SEEDS = FUZZ / "seeds" / "run_script"

# Something only a CozoScript program would contain.
MARKERS = ("?[", ":create", ":put", ":rm", ":replace", "::", "<-", ":=", "<~")


def dict_tokens():
    toks = set()
    grammar = (CORE / "src" / "cozoscript.pest").read_text()
    toks |= set(re.findall(r'"((?:[^"\\]|\\.)+)"', grammar))
    expr = (CORE / "src" / "data" / "expr.rs").read_text()
    toks |= set(re.findall(r'^\s*"([a-z_0-9]+)" => &OP_', expr, re.M))
    rules = (CORE / "src" / "fixed_rule" / "mod.rs").read_text()
    toks |= set(re.findall(r'"([A-Z][A-Za-z]+)"\.to_string\(\)', rules))
    return sorted(toks)


def string_literals(src):
    """Yield the decoded contents of Rust raw and plain string literals."""
    for m in re.finditer(r'r(#*)"(.*?)"\1', src, re.S):
        yield m.group(2)
    for m in re.finditer(r'(?<![r#\w])"((?:[^"\\\n]|\\.)*)"', src):
        try:
            yield bytes(m.group(1), "utf-8").decode("unicode_escape")
        except UnicodeDecodeError:
            pass


def doc_blocks(src):
    yield from re.findall(r"```(?:cozo|cozoscript|datalog)?\n(.*?)```", src, re.S)


def main():
    tokens = dict_tokens()
    with open(FUZZ / "cozoscript.dict", "w") as f:
        f.write("# Generated by gen_corpus.py; do not edit.\n")
        for t in tokens:
            esc = t.replace("\\", "\\\\").replace('"', '\\"')
            f.write(f'"{esc}"\n')

    SEEDS.mkdir(parents=True, exist_ok=True)
    for old in SEEDS.iterdir():
        old.unlink()
    scripts = set()
    for p in list((CORE / "tests").glob("*.rs")) + list((CORE / "src").rglob("*.rs")):
        for s in string_literals(p.read_text()):
            if any(k in s for k in MARKERS) and len(s) < 8192:
                scripts.add(s.strip())
    for p in (CORE.parent / "docs").rglob("*.md"):
        for s in doc_blocks(p.read_text()):
            if any(k in s for k in MARKERS) and len(s) < 8192:
                scripts.add(s.strip())
    for s in scripts:
        name = hashlib.sha1(s.encode()).hexdigest()[:16]
        (SEEDS / name).write_text(s)
    print(f"{len(tokens)} dictionary tokens, {len(scripts)} seed scripts")


main()
